/* Paper III Version 3 (P2SQL, ICSE 2025) translation page: 13-page Compare View.
   Left pane: the original PDF page (assets/v3/pages/page-N.png). Right pane: the Thai article for the
   same page (generated by .build_v3/build_p3v3_pages.js from translation_v3_*.js).
   Uses the Compare View classes of Version 1 (assets/css/interactive.css) with its own v3- ids, so
   the Version 1 driver (assets/js/translation.js) and this one never touch each other's elements.
   Arrow keys turn pages only while the Version 3 panel is on screen. */
(function () {
  'use strict';
  const $ = (id) => document.getElementById('v3-tr-' + id);
  const grid = $('grid'); if (!grid) return;
  const panel = document.getElementById('p3-panel-v3');
  const MAX = 13, FIRST_PRINTED = 1769, KEY = 'p2sql_tr_state';
  const arts = [...grid.querySelectorAll('.thai-page-article')];
  const img = $('img');
  const store = {
    get() { try { return JSON.parse(localStorage.getItem(KEY) || '{}'); } catch (e) { return {}; } },
    set(v) { try { localStorage.setItem(KEY, JSON.stringify(v)); } catch (e) { /* storage unavailable */ } },
  };
  const saved = store.get();
  const q = new URLSearchParams(location.search);
  let page = Math.min(MAX, Math.max(1, +(q.get('p3page') || saved.page || 1)));
  let view = saved.view || 'compare';
  let study = saved.study || 'detailed';

  function save() { store.set({ page, view, study }); }

  function setPage(p, scroll) {
    page = Math.max(1, Math.min(MAX, p));
    arts.forEach((a) => { a.style.display = +a.dataset.page === page ? '' : 'none'; });
    img.src = `assets/v3/pages/page-${page}.png`;
    img.alt = `บทความ P2SQL หน้า ${FIRST_PRINTED + page - 1} (PDF หน้า ${page})`;
    const label = `ICSE 2025 · หน้า ${FIRST_PRINTED + page - 1} (PDF ${page} จาก ${MAX})`;
    $('label').textContent = label;
    $('dock-label').textContent = `หน้า ${page} / ${MAX}`;
    $('select').value = String(page);
    $('prev').disabled = page === 1;
    $('next').disabled = page === MAX;
    save();
    if (scroll) grid.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }

  function setView(v) {
    view = v;
    const paper = $('paper-pane'), thai = $('thai-pane');
    grid.classList.toggle('mode-thai-only', v === 'thai');
    grid.classList.toggle('mode-paper-only', v === 'paper');
    paper.style.display = v === 'thai' ? 'none' : '';
    thai.style.display = v === 'paper' ? 'none' : '';
    document.querySelectorAll('[data-v3-view]').forEach((b) => { b.classList.toggle('active', b.dataset.v3View === v); b.setAttribute('aria-pressed', String(b.dataset.v3View === v)); });
    save();
  }

  function setStudy(s) {
    study = s;
    grid.querySelectorAll('.thai-trans-block').forEach((b) => { b.style.display = s === 'summary' ? 'none' : ''; });
    document.querySelectorAll('[data-v3-study]').forEach((b) => { b.classList.toggle('active', b.dataset.v3Study === s); b.setAttribute('aria-pressed', String(b.dataset.v3Study === s)); });
    save();
  }

  $('select').innerHTML = arts.map((a) => `<option value="${a.dataset.page}">หน้า ${a.dataset.page}: ${a.dataset.title}</option>`).join('');
  $('select').addEventListener('change', (e) => setPage(+e.target.value, true));
  $('prev').addEventListener('click', () => setPage(page - 1, true));
  $('next').addEventListener('click', () => setPage(page + 1, true));
  document.querySelectorAll('[data-v3-view]').forEach((b) => b.addEventListener('click', () => setView(b.dataset.v3View)));
  document.querySelectorAll('[data-v3-study]').forEach((b) => b.addEventListener('click', () => setStudy(b.dataset.v3Study)));
  document.querySelectorAll('[data-v3-goto]').forEach((b) => b.addEventListener('click', () => setPage(+b.dataset.v3Goto, true)));

  window.addEventListener('keydown', (e) => {
    if (!panel || panel.hidden || getComputedStyle(panel).display === 'none') return;
    if (/INPUT|TEXTAREA|SELECT/.test(document.activeElement.tagName)) return;
    if (e.key === 'ArrowRight') { e.stopImmediatePropagation(); setPage(page + 1); }
    else if (e.key === 'ArrowLeft') { e.stopImmediatePropagation(); setPage(page - 1); }
  }, true);

  setPage(page); setView(view); setStudy(study);
})();
