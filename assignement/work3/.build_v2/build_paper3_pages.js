// Assemble the unified Paper III pages. In paper-3/index.html (lesson) and paper-3/translation.html
// (translation), Version 1 (OmniLedger 2018) and Version 2 (Raft-FL 2024) live on the same page as
// two panels, and a dropdown switches between them without leaving paper-3/.
//
//   node build_paper3_pages.js
//
// The script is idempotent. On the first run it converts each original Version 1 page:
//   - removes the old "go to v2/" breadcrumb link and notice banner (lesson page)
//   - wraps the Version 1 content in <div class="p3-panel" id="p3-panel-v1" data-version="v1">
//   - adds the version switcher, the stylesheet and script tags, and the <body> data attributes
// On every run it replaces the block between <!-- P3V2:START --> and <!-- P3V2:END --> with the
// Version 2 panel: p3v2_panel.html for the lesson page, build_translation_v2.js for the translation.
// The Version 1 content itself is not edited; only its links to index.html/translation.html gain ?v=1.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..', '..');
const P3 = path.join(ROOT, 'paper-3');
const INDEX = path.join(P3, 'index.html');
const TRANSLATION = path.join(P3, 'translation.html');
const PANEL = path.join(__dirname, 'p3v2_panel.html');
const { renderPanel: renderTranslationPanel } = require('./build_translation_v2');

const TITLE_V1 = 'Paper III Version 1: OmniLedger (IEEE S&amp;P 2018) · 305432 เครือข่ายเซนเซอร์';
const TITLE_V2 = 'Paper III Version 2: Raft-FL (SEAMS 2024) · 305432 เครือข่ายเซนเซอร์';
const TR_TITLE_V1 = 'บทความแปลไทย Version 1: OmniLedger (Compare View 16 หน้า) · 305432 เครือข่ายเซนเซอร์';
const TR_TITLE_V2 = 'บทความแปลไทย Version 2: Raft-FL (คู่ขนาน 12 หน้า) · 305432 เครือข่ายเซนเซอร์';
const ALIAS = '{"sec-rehearsal":"v2-sec-rehearsal","sec-simulator":"v2-sec-simulator","sec-qna":"v2-sec-qna"}';

function switcher(what) {
  return `<!-- P3SWITCH:START -->
  <div class="p3-switcher" role="region" aria-label="เลือกเวอร์ชันของ Paper III">
    <div class="p3-switcher-inner">
      <div class="p3-switcher-left">
        <label for="p3-version-select">เลือกเวอร์ชัน${what}:</label>
        <select id="p3-version-select" data-p3-select>
          <option value="v2">Version 2: Raft-FL (SEAMS 2024)</option>
          <option value="v1">Version 1: OmniLedger (IEEE S&amp;P 2018)</option>
        </select>
      </div>
      <div class="p3-tabs" role="group" aria-label="สลับเวอร์ชัน">
        <button type="button" data-p3-tab="v1" aria-pressed="false">Version 1 (OmniLedger 2018)</button>
        <button type="button" data-p3-tab="v2" aria-pressed="true">Version 2 (Raft-FL 2024)</button>
      </div>
    </div>
  </div>
  <!-- P3SWITCH:END -->`;
}

function mustReplace(s, re, to, label) {
  if (!re.test(s)) throw new Error(`pattern not found: ${label}`);
  return s.replace(re, to);
}

// Give every Version 2 image its intrinsic width and height (read from the PNG header), so the page
// keeps its layout while lazy images load and links to #sections land in the right place.
function sizeImages(html) {
  return html.replace(/<img (?![^>]*\swidth=)([^>]*?)src="(assets\/v2\/[^"]+\.png)"([^>]*)>/g, (m, pre, src, post) => {
    const buf = fs.readFileSync(path.join(P3, src));
    return `<img ${pre}src="${src}" width="${buf.readUInt32BE(16)}" height="${buf.readUInt32BE(20)}"${post}>`;
  });
}

function v2Block(inner, source) {
  return `<!-- P3V2:START (generated by .build_v2/build_paper3_pages.js from ${source}) -->
  <div class="p3-panel" id="p3-panel-v2" data-version="v2" hidden>
${inner.replace(/\s+$/, '')}
  </div>
  <!-- P3V2:END -->`;
}

function convertIndex(s) {
  // old cross-directory navigation to v2/ (breadcrumb link and banner)
  s = mustReplace(s, /\s*<span class="sep">\/<\/span>\s*<a href="v2\/index\.html"[^>]*>[^<]*<\/a>/, '', 'v1 breadcrumb v2 link');
  s = mustReplace(s, /\s*<!-- Version 2 Quick Switch Notice Banner -->[\s\S]*?(?=\s*<div class="course-meta-bar">)/, '', 'v1 notice banner');
  s = s.replace(/href="translation\.html"/g, 'href="translation.html?v=1"');

  // Version 1 sidebar: a card that switches to Version 2 on the same page
  s = mustReplace(s, /(\n\s*)(<button class="sidebar-modal-trigger paper-ref-pill")/, `$1<a href="?v=2" class="sidebar-action-card" data-p3-switch="v2" title="สลับไป Version 2 ในหน้าเดียวกัน">
          <span class="action-icon" style="font-size: 0.72rem; font-weight: 800;">v2</span>
          <div class="action-text">
            <div class="action-title">ดู Version 2 (Raft-FL)</div>
            <div class="action-desc">SEAMS 2024 · บทความที่ใช้นำเสนอ</div>
          </div>
          <span class="action-arrow">&rarr;</span>
        </a>
$1$2`, 'v1 sidebar modal trigger');

  // head: page title, switcher and Version 2 stylesheets
  s = mustReplace(s, /<title>[^<]*<\/title>/, '<title>Paper III: OmniLedger (2018) และ Raft-FL (2024) · 305432 เครือข่ายเซนเซอร์</title>', 'title');
  s = mustReplace(s, /(<link rel="stylesheet" href="\.\.\/assets\/css\/interactive\.css">)/, `$1
  <link rel="stylesheet" href="assets/p3-version.css">
  <link rel="stylesheet" href="assets/v2/css/raftfl.css">`, 'interactive.css link');

  // body attributes used by assets/p3-version.js
  s = mustReplace(s, /<body data-paper="omniledger">/, `<body data-paper="omniledger" data-title-v1="${TITLE_V1}" data-title-v2="${TITLE_V2}" data-p3-alias='${ALIAS}'>`, 'body');

  // wrap Version 1 and add the switcher above it
  s = mustReplace(s, /(  <!-- ═+ Chapter Layout \(Sidebar \+ Main Content\) ═+ -->\n)(  <div class="chapter-container">)/, `  ${switcher('บทความ Paper III')}

$1  <!-- P3V1:START Version 1 panel (OmniLedger, IEEE S&P 2018) -->
  <div class="p3-panel" id="p3-panel-v1" data-version="v1">
$2`, 'v1 chapter container');
  s = mustReplace(s, /(    <\/main>\n  <\/div>\n)(\n  <!-- ═+ Interactive PDF Quick View Modal)/, `$1  </div>
  <!-- P3V1:END -->

  <!-- P3V2:START -->
  <!-- P3V2:END -->
$2`, 'v1 container end');

  // scripts: the switcher first, then Version 2, then the shared and Version 1 scripts
  s = mustReplace(s, /(\n  )(<script src="\.\.\/assets\/js\/common\.js"><\/script>)/, `$1<script src="assets/p3-version.js"></script>
  <script>window.RAFTFL_PREFIX = 'v2-'; window.RAFTFL_ASSETS = 'assets/v2/';</script>
  <script src="assets/v2/js/raftfl-data.js"></script>
  <script src="assets/v2/js/raftfl-page.js"></script>
  <script src="assets/v2/js/raftfl-sim.js"></script>
  $2`, 'common.js script');
  return s;
}

// Runs in <head> before first paint: picks the version from ?v or the saved choice, so the page
// never shows the other panel for a moment. assets/p3-version.js makes the final choice.
const PREPAINT = `<script data-p3-prepaint>(function () { var q = new URLSearchParams(location.search).get('v'), v = q === '1' || q === 'v1' ? 'v1' : q === '2' || q === 'v2' ? 'v2' : null; if (!v) { try { v = localStorage.getItem('p3_version'); } catch (e) { v = null; } } if (v !== 'v1' && v !== 'v2') v = 'v2'; document.documentElement.setAttribute('data-p3', v); })();</script>`;

function addPrepaint(s) {
  s = s.replace(/\n  <script data-p3-prepaint>[^\n]*<\/script>/, '');
  return mustReplace(s, /(<meta name="viewport"[^>]*>)/, `$1\n  ${PREPAINT}`, 'viewport meta');
}

function convertTranslation(s) {
  s = s.replace(/href="index\.html(#[^"]*)?"/g, (m, h) => `href="index.html?v=1${h || ''}"`);
  s = mustReplace(s, /<title>[^<]*<\/title>/, '<title>บทความแปลไทย Paper III: OmniLedger (2018) และ Raft-FL (2024) · 305432 เครือข่ายเซนเซอร์</title>', 'title');
  s = mustReplace(s, /(<link rel="stylesheet" href="\.\.\/assets\/css\/interactive\.css">)/, `$1
  <link rel="stylesheet" href="assets/p3-version.css">
  <link rel="stylesheet" href="assets/v2/css/raftfl.css">
  <link rel="stylesheet" href="assets/v2/css/translation-v2.css">`, 'interactive.css link');
  s = mustReplace(s, /<body data-paper="omniledger">/, `<body data-paper="omniledger" data-title-v1="${TR_TITLE_V1}" data-title-v2="${TR_TITLE_V2}">`, 'body');
  s = mustReplace(s, /(<!-- ═+ Main Container ═+ -->\n)(<div class="compare-view-container">)/, `${switcher('บทความแปล')}

$1<!-- P3V1:START Version 1 panel (OmniLedger Compare View and learning dock) -->
<div class="p3-panel" id="p3-panel-v1" data-version="v1">
$2`, 'v1 compare container');
  s = mustReplace(s, /(\n<\/div>\n)(\n<!-- JavaScript Modules -->)/, `$1</div>
<!-- P3V1:END -->

<!-- P3V2:START -->
<!-- P3V2:END -->
$2`, 'v1 dock end');
  s = mustReplace(s, /(\n)(<script src="\.\.\/assets\/js\/common\.js"><\/script>)/, `$1<script src="assets/p3-version.js"></script>
<script src="assets/v2/js/translation-v2.js"></script>
$2`, 'common.js script');
  return s;
}

function checkIds(file, s, first) {
  const ids = [...s.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  const dup = [...new Set(ids.filter((id, i) => ids.indexOf(id) !== i))];
  console.log(`${first ? 'converted' : 'updated'} ${path.relative(ROOT, file)} (${(s.length / 1024).toFixed(0)} KB, ${ids.length} ids)`);
  if (dup.length) { console.error('duplicate ids:', dup.join(', ')); process.exit(1); }
}

function build(file, convert, inner, source) {
  let s = fs.readFileSync(file, 'utf8');
  const first = !s.includes('id="p3-panel-v1"');
  if (first) s = convert(s);
  s = addPrepaint(s);
  s = mustReplace(s, /<!-- P3SWITCH:START -->[\s\S]*?<!-- P3SWITCH:END -->/, () => switcher(file === INDEX ? 'บทความ Paper III' : 'บทความแปล'), 'P3SWITCH markers');
  s = mustReplace(s, /<!-- P3V2:START[\s\S]*?<!-- P3V2:END -->/, () => v2Block(sizeImages(inner), source), 'P3V2 markers');
  fs.writeFileSync(file, s);
  checkIds(file, s, first);
}

function main() {
  const panel = fs.readFileSync(PANEL, 'utf8');
  build(INDEX, convertIndex, `  <div class="chapter-container">\n${panel.replace(/\s+$/, '')}\n  </div>`, 'p3v2_panel.html');
  build(TRANSLATION, convertTranslation, `    ${renderTranslationPanel()}`, 'translation_v2.js');
}

module.exports = { main };

if (require.main === module) main();
