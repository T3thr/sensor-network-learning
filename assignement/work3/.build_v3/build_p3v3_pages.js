function replaceBlock(file, inner, label) {
  let s = fs.readFileSync(file, 'utf8');
  const re = /<!-- P3V3:START[\s\S]*?<!-- P3V3:END -->/;
  if (!re.test(s)) throw new Error('P3V3 markers missing in ' + file);
  const block = `<!-- P3V3:START (generated by .build_v3/build_p3v3_pages.js: ${label}) -->
  <div class="p3-panel" id="p3-panel-v3" data-version="v3">
${inner}
  </div>
  <!-- P3V3:END -->`;
  s = s.replace(re, () => block);
  return s;
}

